/**
 * 手工字符画
 *
 * ⚠️ 全部为**纯半角 ASCII**（`+ - | / \ _ . ' * = #`）。
 * 原因是一条硬约束，不是审美偏好：
 *
 *   fontsource 按 unicode-range 分片，`latin` 分片**不含制表符**（U+2500 区段）
 *   与方块元素（U+2580 区段）。画里一旦出现 `─│┌┐█░`，它们就会回落到系统字体，
 *   列宽随之改变 —— **整幅画立刻错位**。
 *
 * 同理禁止中文与 emoji（全角 = 2 列）。需要中文标注时，
 * 用 `grid.ts` 的 `columnToIndex` 在画外单独定位（见 MilestoneCard）。
 *
 * 书写约定：每幅画的**最左一列从模板字符串的第 0 列开始**，
 * `buildGrid` 会剥掉公共缩进，因此只需保证相对缩进正确。
 * 边框对齐由 `tests/unit/art/art.test.ts` 守住。
 */

